function injectTranslations(filePath) {
  let code = fs.readFileSync(filePath, 'utf8');

  for (const [lang, kvMap] of Object.entries(NEW_TRANSLATIONS)) {
    const searchToken = `"${lang}": {`;
    const idx = code.indexOf(searchToken);
    if (idx !== -1) {
      let injectStr = '\n';
      const endLangIdx = code.indexOf('\n  },', idx);
      const section = code.substring(idx, endLangIdx === -1 ? idx + 30000 : endLangIdx);
      
      for (const [k, v] of Object.entries(kvMap)) {
        const keyToken = `"${k}":`;
        if (!section.includes(keyToken)) {
          const escapedVal = JSON.stringify(v);
          injectStr += `    "${k}": ${escapedVal},\n`;
        }
      }
      const insertPoint = idx + searchToken.length;
      code = code.substring(0, insertPoint) + injectStr + code.substring(insertPoint);
    }
  }

  // Also enhance applyTranslations to support data-i18n-value
  if (!code.includes('data-i18n-value')) {
    const applyTarget = `// 2. Placeholders with data-i18n-placeholder`;
    const applyValueCode = `// 1.5 Default input values with data-i18n-value
    document.querySelectorAll('[data-i18n-value]').forEach(el => {
      const key = el.getAttribute('data-i18n-value');
      const val = t(key);
      if (val && (!el.value || el.dataset.userEdited !== 'true')) {
        el.value = val;
      }
    });

    // 2. Placeholders with data-i18n-placeholder`;
    code = code.replace(applyTarget, applyValueCode);
  }

  fs.writeFileSync(filePath, code, 'utf8');
  console.log('Injected translations into:', filePath);
}

