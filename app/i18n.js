  // State Management with Cross-Page & URL Param Sync
  function getInitialLanguage() {
    try {
      const urlLang = new URLSearchParams(window.location.search).get('lang');
      if (urlLang && TRANSLATIONS[urlLang]) return urlLang;
      const saved = localStorage.getItem('haichain-lang');
      if (saved && TRANSLATIONS[saved]) return saved;
    } catch (_) {}
    return 'en';
  }

  let currentLang = getInitialLanguage();

  function t(key, fallback) {
    const dict = TRANSLATIONS[currentLang] || TRANSLATIONS['en'];
    return dict[key] || TRANSLATIONS['en'][key] || fallback || key;
  }

  function setLanguage(langCode) {
    if (!TRANSLATIONS[langCode]) return;
    currentLang = langCode;
    try {
      localStorage.setItem('haichain-lang', langCode);
    } catch (_) {}

    document.documentElement.setAttribute('lang', langCode);
    // RTL handling for Modern Hebrew
    document.documentElement.setAttribute('dir', langCode === 'he' ? 'rtl' : 'ltr');

    // Update URL query without page reload
    try {
      const u = new URL(window.location);
      u.searchParams.set('lang', langCode);
      window.history.replaceState({}, '', u);
    } catch (_) {}

    applyTranslations();
    updateSwitcherUI();
    syncNavigationLinks();

    window.dispatchEvent(new CustomEvent('haichain:languageChanged', { detail: { lang: langCode } }));
  }

  function syncNavigationLinks() {
    document.querySelectorAll('a[href]').forEach(a => {
      const h = a.getAttribute('href');
      if (!h || h.startsWith('#') || h.startsWith('javascript:')) return;
      if (h.startsWith('/dashboard') || h === '/' || h.startsWith('/?') || h.startsWith('/app') || h.startsWith('/whitepaper')) {
        try {
          const u = new URL(h, window.location.origin);
          u.searchParams.set('lang', currentLang);
          a.setAttribute('href', u.pathname + u.search + u.hash);
        } catch (_) {}
      }
    });
  }

  function applyTranslations() {
    // 1. Text elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const val = t(key);
      if (val !== undefined && val !== null) {
        if (val.includes('<') || val.includes('&')) {
          el.innerHTML = val;
        } else {
          el.textContent = val;
        }
      }
    });

    // 2. Placeholders with data-i18n-placeholder
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      const val = t(key);
      if (val) el.setAttribute('placeholder', val);
    });

    // 3. Titles with data-i18n-title
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      const val = t(key);
      if (val) el.setAttribute('title', val);
    });

    syncNavigationLinks();
  }

